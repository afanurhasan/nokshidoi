/**
 * হোয়াটসঅ্যাপ প্রি-ফিল্ড মেসেজ তৈরির ফাংশন (সম্পূর্ণ বাংলা)
 */
export function getWhatsAppOrderUrl(product = null, customNote = "") {
  const rawNumber = BUSINESS_CONFIG.whatsappNumber.replace(/[^0-9]/g, "");
  let message = "";

  if (product) {
    const availabilityText =
      product.availability === "wholesale"
        ? "পাইকারি"
        : product.availability === "retail"
        ? "খুচরা"
        : "খুচরা ও পাইকারি";

    message = `আসসালামু আলাইকুম নকশী দই ভাণ্ডার,\n\nআমি এই পণ্যটি অর্ডার করতে চাই:\n• পণ্যের নাম: ${product.name}\n• সাইজ: ${product.size}\n• মূল্য: ${BUSINESS_CONFIG.currency}${product.price}\n• ধরন: ${availabilityText}\n\nদয়া করে প্রাপ্যতা ও ডেলিভারির সময় নিশ্চিত করুন। ধন্যবাদ!`;
  } else if (customNote) {
    message = `আসসালামু আলাইকুম নকশী দই ভাণ্ডার,\n\n${customNote}`;
  } else {
    message = `আসসালামু আলাইকুম নকশী দই ভাণ্ডার,\n\nআমি আপনাদের খাঁটি দই অর্ডার করতে আগ্রহী। আজকের তাজা ব্যাচ ও ডেলিভারি সম্পর্কে বিস্তারিত জানতে চাই।`;
  }

  return `https://wa.me/${rawNumber}?text=${encodeURIComponent(message)}`;
}

