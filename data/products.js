/**
 * স্লাগ বা আইডি দিয়ে প্রোডাক্ট খোঁজার হেল্পার
 */
export function getProductBySlugOrId(identifier) {
  if (!identifier) return null;
  const cleanId = decodeURIComponent(String(identifier)).trim().toLowerCase();
  return (
    PRODUCTS.find(
      (p) => p.slug.toLowerCase() === cleanId || p.id.toLowerCase() === cleanId
    ) || null
  );
}

/**
 * ফিল্টারিং হেল্পার
 */
export function getFilteredProducts({ category = "all", availability = "all", search = "" } = {}) {
  return PRODUCTS.filter((p) => {
    if (category && category !== "all" && p.category !== category) {
      return false;
    }
    if (availability && availability !== "all") {
      if (availability === "retail" && p.availability === "wholesale") return false;
      if (availability === "wholesale" && p.availability === "retail") return false;
    }
    if (search && search.trim() !== "") {
      const term = search.toLowerCase();
      const matchName = p.name.toLowerCase().includes(term);
      const matchDesc = p.shortDescription.toLowerCase().includes(term);
      const matchSize = p.size.toLowerCase().includes(term);
      if (!matchName && !matchDesc && !matchSize) return false;
    }
    return true;
  });
}
